#!/usr/bin/env node
/**
 * LumiIQ — offline replay of recorded evaluation sessions (Phase B)
 *
 * Runs a recorded session (eval/sessions/<id>.json) through the REAL gaze
 * modules under Node:
 *
 *   landmarks ─▶ GazeFeatures.extract ─▶ GazeCalibration (re-fitted from the
 *   frames each calibration point was built from) ─▶ GazeStabilizer ─▶
 *   DwellController (rest period, on the recorded key layout)
 *
 * and measures the result with eval/metrics.js. With the recorded options the
 * replay must reproduce the gaze the live app showed (`checks` says how
 * closely); with other options it shows what a change would have done to the
 * same recording, so variants are compared on identical data.
 *
 * Usage:
 *   node eval/replay.js                       replay every session in eval/sessions/
 *   node eval/replay.js <file-or-folder> …    replay these
 *     --degree 1|2            polynomial degree of the model
 *     --cv loto|interleaved   how lambda and the in-app estimate are cross-validated
 *     --smoothing 0.05..0.45  one smoothing level for the whole session
 *     --recompute             rebuild the features from the recorded landmarks
 *     --json                  print the full result as JSON
 *
 * Numbers from sessions of a real person are "replayed real". A session
 * marked `synthetic` (generated by a test or a pipeline check) is labelled
 * "synthetic" and is never a result.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const Features = require('../gaze/gaze-features.js');
const { GazeCalibration } = require('../gaze/gaze-calibration.js');
const { GazeStabilizer } = require('../gaze/gaze-stabilizer.js');
const { DwellController } = require('../gaze/dwell-controller.js');
const M = require('./metrics.js');
const { SessionRecorder } = require('./session-recorder.js');

const SESSIONS_DIR = path.join(__dirname, 'sessions');
const FEATURE_FIELDS = ['f0', 'f1', 'f2', 'f3', 'f4', 'f5', 'f6', 'f7', 'f8', 'f9'];

/**
 * Replay options. `null` means "as recorded".
 * `features`, `calibration` and `stabilizer` are passed to the gaze modules
 * as their own options (used for the Phase C variants).
 */
const DEFAULTS = {
  degree: 2,            // polynomial degree of the regression
  cv: 'loto',           // 'loto' | 'interleaved'
  smoothing: null,      // null: the smoothing each phase was recorded with
  recompute: false,     // rebuild features from the recorded landmarks
  features: null,       // options for GazeFeatures.extract
  calibration: null,    // options for GazeCalibration
  stabilizer: null,     // options for GazeStabilizer
};

function loadSession(file) {
  const session = JSON.parse(fs.readFileSync(file, 'utf8'));
  const problems = SessionRecorder.validate(session);
  if (problems.length) throw new Error(`${path.basename(file)}: ${problems.join('; ')}`);
  return session;
}

/** Every *.json session in a folder (sorted), or the single file given. */
function findSessions(target) {
  if (!fs.existsSync(target)) return [];
  if (fs.statSync(target).isFile()) return [target];
  return fs.readdirSync(target).filter((f) => f.endsWith('.json')).sort().map((f) => path.join(target, f));
}

const label = (session) => (session.synthetic === true ? 'synthetic' : 'replayed real');

// ── Stage 1: features ────────────────────────────────────────────────

/** Per frame: the feature vector (or null) and its confidence. */
function frameFeatures(session, opts) {
  const col = (name) => session.frameFields.indexOf(name);
  const fi = FEATURE_FIELDS.map(col), ci = col('conf');
  const recorded = session.frames.map((f) => (f[fi[0]] == null ? null : fi.map((i) => f[i])));
  if (!opts.recompute && !opts.features) {
    return { features: recorded, conf: session.frames.map((f) => f[ci] || 0), check: { featureFrames: 0, featureMaxDiff: null } };
  }
  const settings = { earThreshold: 0.18, activeEye: 'both', swapEyes: false, ...(session.settings || {}) };
  const features = [], conf = [];
  let frames = 0, maxDiff = 0;
  for (let i = 0; i < session.frames.length; i++) {
    const lm = session.landmarks[i];
    if (!lm) { features.push(null); conf.push(0); continue; }
    const matrix = session.matrices[i] ? { data: session.matrices[i] } : null;
    const fx = Features.extract(Features.unpack(lm), matrix, settings, opts.features || undefined);
    features.push(fx.features || null);
    conf.push(fx.features ? Features.confidence(fx.features) : 0);
    if (fx.features && recorded[i] && !opts.features) {
      frames++;
      for (let k = 0; k < fx.features.length; k++) maxDiff = Math.max(maxDiff, Math.abs(fx.features[k] - recorded[i][k]));
    }
  }
  return { features, conf, check: { featureFrames: frames, featureMaxDiff: frames ? maxDiff : null } };
}

// ── Stage 2: calibration ─────────────────────────────────────────────

/** Re-fit one recorded calibration from the frames each of its points was built from. */
function fitCalibration(session, name, features, opts) {
  const record = (session.calibrations || []).filter((c) => c.name === name && c.report && c.report.ok).pop();
  if (!record) return null;
  const cal = new GazeCalibration({ degree: opts.degree, cv: opts.cv, ...(opts.calibration || {}) });
  let target = cal.begin(record.points);
  for (const point of record.targets.slice().sort((a, b) => a.index - b.index)) {
    if (!target || Math.abs(target.x - point.x) > 1e-9 || Math.abs(target.y - point.y) > 1e-9) {
      throw new Error(`${session.id}: calibration ${name}, point ${point.index} is not where the ${record.points}-point layout puts it`);
    }
    for (const i of point.frames) if (features[i]) cal.addSample(features[i]);
    target = cal.commitPoint().next;
  }
  const report = cal.train({ width: session.screen.width, height: session.screen.height });
  return { name, points: record.points, endT: record.t1, model: cal, report };
}

// ── Stage 3: prediction and smoothing ────────────────────────────────

/** The smoothing setting in effect for each frame. */
function frameSmoothing(session, opts) {
  const base = session.settings && session.settings.smoothingFactor != null ? session.settings.smoothingFactor : 0.35;
  const out = new Array(session.frames.length).fill(opts.smoothing != null ? opts.smoothing : base);
  if (opts.smoothing != null) return out;
  for (const phase of session.phases || []) {
    if (phase.smoothing == null) continue;
    const end = phase.frame1 == null ? session.frames.length : phase.frame1;
    for (let i = phase.frame0; i < end; i++) out[i] = phase.smoothing;
  }
  return out;
}

/** Features → model → smoother, frame by frame, as the engine does it live. */
function replayGaze(session, opts) {
  const col = (name) => session.frameFields.indexOf(name);
  const it = col('t'), ir = col('reason'), ipx = col('predX'), ipy = col('predY');
  const reasons = session.enums.reason;
  const { features, conf, check } = frameFeatures(session, opts);
  const calibrations = {};
  for (const name of ['cal9', 'cal16']) {
    const fit = fitCalibration(session, name, features, opts);
    if (fit && fit.report && fit.report.ok) calibrations[name] = fit;
  }
  const order = Object.values(calibrations).sort((a, b) => a.endT - b.endT);
  const smoothing = frameSmoothing(session, opts);
  const { width, height } = session.screen;
  const stabilizer = new GazeStabilizer({ width, height, ...GazeStabilizer.paramsFor(smoothing[0]), ...(opts.stabilizer || {}) });

  const gaze = [], raw = [];
  for (let i = 0; i < session.frames.length; i++) {
    const frame = session.frames[i], t = frame[it], reason = reasons[frame[ir]];
    let active = null;
    for (const c of order) if (t >= c.endT) active = c;
    let pred = null;
    if (reason === 'calibrating') pred = null;                       // samples were being collected, no gaze
    else if (!active) {                                              // before the first calibration: the engine's rough mapping
      if (frame[ipx] != null && frame[ipy] != null) pred = { x: frame[ipx], y: frame[ipy] };
    } else if (features[i] && conf[i] >= 0.2) {
      const norm = active.model.predict(features[i]);
      pred = { x: norm.x * width, y: norm.y * height };
    }
    raw.push(pred);
    if (!pred) { gaze.push(null); continue; }
    stabilizer.setParams(GazeStabilizer.paramsFor(smoothing[i]));
    gaze.push(stabilizer.process(pred.x, pred.y, t, conf[i]));
  }
  return { features, conf, calibrations, gaze, raw, check };
}

/**
 * How closely the replay matches what was recorded live, over the calibrated
 * frames that have both: the model's output before smoothing (raw) and the
 * smoothed gaze. The smoother holds the cursor inside a 2.5 px deadband, so a
 * tiny difference can tip a single frame over that threshold; hence the mean too.
 */
function compareGaze(session, run) {
  const recorded = M.recordedGaze(session);
  const col = (name) => session.frameFields.indexOf(name);
  const it = col('t'), ipx = col('predX'), ipy = col('predY');
  const firstCal = Math.min(...Object.values(run.calibrations).map((c) => c.endT));
  let frames = 0, sum = 0, maxDiff = 0, rawMax = 0;
  for (let i = 0; i < run.gaze.length; i++) {
    const f = session.frames[i];
    if (!run.gaze[i] || !recorded[i] || !(f[it] >= firstCal)) continue;
    const d = Math.hypot(run.gaze[i].x - recorded[i].x, run.gaze[i].y - recorded[i].y);
    frames++; sum += d; maxDiff = Math.max(maxDiff, d);
    if (run.raw[i] && f[ipx] != null) rawMax = Math.max(rawMax, Math.hypot(run.raw[i].x - f[ipx], run.raw[i].y - f[ipy]));
  }
  if (!frames) return { gazeFrames: 0, gazeMaxDiffPx: null, gazeMeanDiffPx: null, rawMaxDiffPx: null };
  return { gazeFrames: frames, gazeMaxDiffPx: maxDiff, gazeMeanDiffPx: sum / frames, rawMaxDiffPx: rawMax };
}

// ── Stage 4: dwell, for the rest period ──────────────────────────────

/** Re-run the real dwell controller over the rest period, on the recorded key layout. */
function replayRestDwell(session, run) {
  const phase = (session.phases || []).find((p) => p.name === 'rest');
  const keys = session.layouts && session.layouts.keyboard;
  const live = session.rest ? (session.rest.activations || []).length : null;
  if (!phase || !keys) return { live, replayedDwell: null, labels: [] };
  const settings = session.settings || {};
  const it = session.frameFields.indexOf('t');
  const under = (x, y) => keys.find((k) => x >= k.x && x <= k.x + k.w && y >= k.y && y <= k.y + k.h) || null;
  let hitAt = -Infinity, hit = null, now = 0;
  const labels = [];
  const dwell = new DwellController({
    dwellTime: settings.dwellTimeMs || 1200,
    adaptive: true,
    // The engine looks up the target under the gaze at most every 50 ms.
    hitTest: (x, y) => { if (now - hitAt >= 50) { hitAt = now; hit = under(x, y); } return hit; },
    getRect: (k) => ({ left: k.x, top: k.y, right: k.x + k.w, bottom: k.y + k.h }),
    onActivate: (k) => labels.push(k.label),
  });
  dwell.setParams({ autoActivate: (phase.mode || settings.selectionMode) !== 'blink', repeatWhileLooking: settings.dwellRepeat === true });
  // The engine's running average of confidence covers every frame that produced a prediction.
  let avg;
  const end = phase.frame1 == null ? session.frames.length : phase.frame1;
  for (let i = 0; i < end; i++) {
    const g = run.gaze[i];
    if (g) avg = Features.smoothConfidence(avg, run.conf[i]);
    if (i < phase.frame0) continue;
    now = session.frames[i][it];
    if (!g) { dwell.noGaze(now); continue; }
    dwell.setDwellTime((settings.dwellTimeMs || 1200) * Features.dwellScale(avg));
    dwell.update(g.x, g.y, now);
  }
  return { live, replayedDwell: labels.length, labels };
}

// ── The whole session ────────────────────────────────────────────────

/**
 * Replay one session.
 * @returns {{id, label, options, checks, calibrations, analysis, m1, rest}}
 */
function replaySession(session, options = {}) {
  const problems = SessionRecorder.validate(session);
  if (problems.length) throw new Error(`Session cannot be replayed: ${problems.join('; ')}`);
  const opts = { ...DEFAULTS, ...options };
  const geom = M.sessionGeometry(session);
  const run = replayGaze(session, opts);

  const analysis = M.analyseSession(session, { gaze: run.gaze });
  analysis.inApp = {};
  for (const name of ['cal9', 'cal16']) {
    const c = run.calibrations[name];
    analysis.inApp[name] = c ? M.inAppFromReport(c.report, c.points, geom) : null;
  }

  // AUDIT M1: the app's own estimate under each cross-validation method, next to
  // the error actually measured on the held-out targets with that model.
  const m1 = {};
  for (const [name, set] of [['cal9', 'val9'], ['cal16', 'val16']]) {
    if (!run.calibrations[name]) continue;
    m1[name] = {};
    for (const cv of ['loto', 'interleaved']) {
      const other = cv === opts.cv ? run : replayGaze(session, { ...opts, cv });
      const c = other.calibrations[name];
      if (!c) continue;
      m1[name][cv] = {
        inApp: M.inAppFromReport(c.report, c.points, geom),
        heldOut: M.validationSummary(session, { set }, M.WINDOWS.standard, other.gaze).accuracy,
        lambda: { x: c.report.lambdaX, y: c.report.lambdaY },
      };
    }
  }

  return {
    id: session.id,
    label: label(session),
    options: { degree: opts.degree, cv: opts.cv, smoothing: opts.smoothing, recompute: opts.recompute,
               features: opts.features, calibration: opts.calibration, stabilizer: opts.stabilizer },
    checks: { ...run.check, ...compareGaze(session, run) },
    calibrations: run.calibrations,
    analysis,
    m1,
    rest: replayRestDwell(session, run),
  };
}

/** Mean ± SD across sessions of one figure (`pick(result)`), with the ids that had it. */
function aggregate(results, pick) {
  const have = results.map((r) => ({ id: r.id, v: pick(r) })).filter((x) => typeof x.v === 'number' && Number.isFinite(x.v));
  return { ...M.meanSd(have.map((x) => x.v)), ids: have.map((x) => x.id) };
}

// ── Command line ─────────────────────────────────────────────────────

function parseArgs(argv) {
  const options = {}, targets = [];
  let json = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--json') json = true;
    else if (a === '--recompute') options.recompute = true;
    else if (a === '--degree') options.degree = parseInt(argv[++i], 10);
    else if (a === '--cv') options.cv = argv[++i];
    else if (a === '--smoothing') options.smoothing = parseFloat(argv[++i]);
    else targets.push(a);
  }
  return { options, targets, json };
}

function describe(result) {
  const px = (v) => (v == null ? 'not measured' : `${v.toFixed(1)} px`);
  const deg = (v) => (v == null ? '' : ` / ${v.toFixed(2)}°`);
  const both = (m) => (m.px == null ? 'not measured' : `${px(m.px)}${deg(m.deg)}`);
  const o = result.options;
  const lines = [
    `${result.id} [${result.label}]  degree ${o.degree}, cv ${o.cv}, smoothing ${o.smoothing == null ? 'as recorded' : o.smoothing}`,
    `  replay check over ${result.checks.gazeFrames} frames: model output within ${px(result.checks.rawMaxDiffPx)} of the live one; smoothed gaze within ${px(result.checks.gazeMaxDiffPx)} (mean ${px(result.checks.gazeMeanDiffPx)})`,
  ];
  for (const set of ['val9', 'val16']) {
    const v = result.analysis.validation[set].standard;
    lines.push(`  ${set}: accuracy x ${both(v.accuracy.x)}, y ${both(v.accuracy.y)}; precision x ${both(v.precision.x)}, y ${both(v.precision.y)}; p95 ${both(v.p95)}  (${v.targets} targets)`);
  }
  for (const name of ['turn', 'tilt', 'lean']) {
    const v = result.analysis.head[name];
    lines.push(`  head ${name}: accuracy x ${both(v.accuracy.x)}, y ${both(v.accuracy.y)}  (${v.targets} targets)`);
  }
  for (const [name, m] of Object.entries(result.m1)) {
    for (const cv of Object.keys(m)) {
      lines.push(`  ${name} in-app estimate (${cv}): x ${both(m[cv].inApp.x)}, y ${both(m[cv].inApp.y)}  |  held-out: x ${both(m[cv].heldOut.x)}, y ${both(m[cv].heldOut.y)}`);
    }
  }
  lines.push(`  rest: ${result.rest.live == null ? 'not recorded' : result.rest.live + ' live activation(s)'}, ${result.rest.replayedDwell == null ? 'dwell not replayed' : result.rest.replayedDwell + ' on dwell replay'}`);
  return lines.join('\n');
}

function main(argv) {
  const { options, targets, json } = parseArgs(argv);
  const files = (targets.length ? targets : [SESSIONS_DIR]).flatMap(findSessions);
  if (!files.length) {
    console.log('No session files found. Record one with the evaluation wizard (see docs/RECORDING.md).');
    return 0;
  }
  const results = [];
  for (const file of files) {
    try { results.push(replaySession(loadSession(file), options)); }
    catch (err) { console.error(`Skipped ${path.basename(file)}: ${err.message}`); }
  }
  if (json) {
    console.log(JSON.stringify(results.map(({ calibrations, ...rest }) => rest), null, 1));
  } else {
    for (const r of results) console.log(describe(r) + '\n');
  }
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { DEFAULTS, loadSession, findSessions, label, frameFeatures, fitCalibration, replayGaze,
                   compareGaze, replayRestDwell, replaySession, aggregate, describe, SESSIONS_DIR };
